#!/usr/bin/env python
"""Generate paper/tables/benchmark.tex from analysis/data/corrected_summary.csv.

Corrected-protocol benchmark (dev-selected LR, 3 seeds, NER prefix-space fix) for
the four instruments the political-science paper compares. Run from repo root:
  python analysis/make_benchmark_table.py
"""
import csv

MODELS = [
    ("ConfliBERT-2021", "ConfliBERT"),
    ("ModernBERT-base", "ModernBERT"),
    ("ConfliBERT-v2-wsd", "ConfliBERT-Modern"),
    ("ConfliBERT-v2-wsd-TAPT", "ConfliBERT-Modern+TAPT"),
]
TASKS = [
    ("BBC_News", "BBC News (topic, binary)"),
    ("20news", "20 Newsgroups (topic, binary)"),
    ("satp_relevant", "SATP relevance (multilabel)"),
    ("cameo_class", "CAMEO event class (multiclass)"),
    ("insightCrime", "InsightCrime (multilabel)"),
    ("IndiaPoliceEvents_sents", "IPE sentences (multilabel)"),
    ("IndiaPoliceEvents_docs", "IPE documents (multilabel)"),
    ("cameo_ner", "CAMEO actors (NER)"),
    ("re3d", "re3d entities (NER)"),
]

rows = list(csv.DictReader(open("analysis/data/corrected_summary.csv")))
d = {(r["task"], r["model"]): (float(r["mean_primary"]), float(r["sd_primary"]))
     for r in rows}

# Emit the FULL tabular environment: \input of a bare row list inside tabular
# breaks under the post-2020 LaTeX file-hook system (Misplaced \noalign).
lines = [
    r"\begin{tabular}{lcccc}",
    r"\toprule",
    r"Task & ConfliBERT & ModernBERT & ConfliBERT & +TAPT \\",
    r" & (2021) & (base) & (Modern) & \\",
    r"\midrule",
]
for task, disp in TASKS:
    vals = [d[(task, m)] for m, _ in MODELS]
    best = max(v[0] for v in vals)
    cells = []
    for mean, sd in vals:
        cell = f"{100*mean:.1f} \\std{{{100*sd:.1f}}}"
        if mean == best:
            cell = f"\\textbf{{{100*mean:.1f}}} \\std{{{100*sd:.1f}}}"
        cells.append(cell)
    lines.append(f"{disp} & " + " & ".join(cells) + r" \\")

means = []
for m, _ in MODELS:
    vs = [d[(t, m)][0] for t, _ in TASKS]
    means.append(100 * sum(vs) / len(vs))
best = max(means)
mean_cells = [f"\\textbf{{{v:.1f}}}" if v == best else f"{v:.1f}" for v in means]
lines.append(r"\midrule")
lines.append("Nine-task mean & " + " & ".join(mean_cells) + r" \\")
lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")

with open("paper/tables/benchmark.tex", "w") as fh:
    fh.write("% generated by analysis/make_benchmark_table.py; do not edit by hand\n")
    fh.write("\n".join(lines) + "\n")
print("wrote paper/tables/benchmark.tex")
